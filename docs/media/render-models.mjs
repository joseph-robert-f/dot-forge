// Renders real exported STLs to transparent PNGs for the media pages.
// Input: a directory holding <run>.stl and <run>.measure.json, copied from
// build/<run>/exports/model.stl and build/<run>/native/measure.json.
// Needs: Node 18+, playwright (with Chromium) and three@0.170.0 resolvable from
// this script. Output: docs/media/src/renders/<name>.png, and anchors.js with the
// projected position of each named feature for the layout pages.
// Usage, from the repository root:
//   node docs/media/render-models.mjs path/to/models
import { chromium } from 'playwright';
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const threeRoot = path.dirname(path.dirname(require.resolve('three')));
const models = path.resolve(process.argv[2] || 'models');
const out = path.resolve('docs/media/src/renders');
mkdirSync(out, { recursive: true });

const PASS = '#3f6f5a', FAIL = '#c4562f';
const measure = (run) => JSON.parse(readFileSync(path.join(models, `${run}.measure.json`), 'utf8'));
const holes = (run) => measure(run).cylinders.filter((c) => c.kind === 'void' && c.angle_rad > 6.28);
const top = (run) => measure(run).size_mm[2];
const ring = (run, x, y, color, extra = {}) => ({ x, y, z: top(run), r: 3.1, color, weight: .2, ...extra });
const plateRings = (run, wanted) => {
  const actual = holes(run).map((h) => h.position_mm);
  const at = (p) => actual.some((a) => Math.hypot(a[0] - p[0], a[1] - p[1]) < .05);
  return [
    ...wanted.map((p) => (at(p) ? ring(run, ...p, PASS) : ring(run, ...p, FAIL, { dashed: true }))),
    ...actual.filter((a) => !wanted.some((p) => Math.hypot(a[0] - p[0], a[1] - p[1]) < .05)).map((a) => ring(run, ...a, FAIL)),
  ];
};
const WANTED = [[6, 6], [54, 6], [6, 34], [54, 34]];
const anchorsFor = (run, points) => Object.fromEntries(points.map(([k, x, y]) => [k, [x, y, top(run)]]));

const jobs = [
  { name: 'plate-hero', run: 'plate-002', width: 760, height: 560, view: [-.75, -1.25, 1.05], zoom: 1.0,
    anchors: anchorsFor('plate-002', [['hole', 6, 6], ['corner', 58.8, 38.8]]) },
  { name: 'plate-001', run: 'plate-001', width: 640, height: 420, view: [-.35, -.95, 1.6], zoom: .98,
    rings: plateRings('plate-001', WANTED), anchors: anchorsFor('plate-001', [['want', 54, 6], ['got', 52, 6]]) },
  { name: 'plate-002', run: 'plate-002', width: 640, height: 420, view: [-.35, -.95, 1.6], zoom: .98,
    rings: plateRings('plate-002', WANTED) },
  { name: 'plate-demo-001', run: 'plate-001', width: 380, height: 300, view: [-.35, -.95, 1.6], zoom: .95,
    rings: plateRings('plate-001', WANTED) },
  { name: 'plate-demo-002', run: 'plate-002', width: 380, height: 300, view: [-.35, -.95, 1.6], zoom: .95,
    rings: plateRings('plate-002', WANTED) },
  { name: 'plate', run: 'plate-002', width: 520, height: 420, view: [-.8, -1.2, 1.1] },
  { name: 'knob', run: 'knob', width: 520, height: 420, view: [-.8, -1.2, 1.25], zoom: 1.12, targetZ: .45 },
  { name: 'stepped-block', run: 'stepped-block', width: 520, height: 420, view: [-.9, -1.15, .95], zoom: 1.1 },
];

const anchors = {};
const browser = await chromium.launch();
for (const job of jobs) {
  const page = await browser.newPage({ viewport: { width: job.width, height: job.height }, deviceScaleFactor: 2 });
  await page.route('https://local.three/**', (route) => {
    const file = path.join(threeRoot, new URL(route.request().url()).pathname);
    route.fulfill({ body: readFileSync(file), contentType: 'text/javascript', headers: { 'Access-Control-Allow-Origin': '*' } });
  });
  const stl = readFileSync(path.join(models, `${job.run}.stl`));
  await page.addInitScript(({ cfg, bytes }) => {
    window.CONFIG = { ...cfg, stl: new Uint8Array(bytes).buffer };
  }, { cfg: { ...job, scale: 2 }, bytes: [...stl] });
  await page.goto(pathToFileURL(path.resolve('docs/media/src/model-view.html')).href);
  await page.waitForFunction(() => window.READY === true, null, { timeout: 30000 });
  await page.locator('canvas').screenshot({ path: path.join(out, `${job.name}.png`), omitBackground: true });
  anchors[job.name] = await page.evaluate(() => window.ANCHORS);
  await page.close();
}
await browser.close();
writeFileSync(path.join(out, 'anchors.js'), `// Generated by render-models.mjs.\nwindow.ANCHORS = ${JSON.stringify(anchors, null, 1)};\n`);
